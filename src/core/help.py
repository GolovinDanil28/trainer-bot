"""Справка: что бот умеет и чего не умеет.

Список команд здесь — данные, а не строка в тексте. Карточка рендерится из него,
поэтому команда не может появиться в боте и отсутствовать в справке: набор
сверяется тестом с тем, что реально зарегистрировано в приложении.

Telegram и базы здесь нет: на вход строка, на выходе «это просьба о справке?».
"""

import re
from dataclasses import dataclass

_PUNCTUATION = re.compile(r"[^\w\s]+", re.UNICODE)
_SPACES = re.compile(r"\s+")


@dataclass(frozen=True, slots=True)
class CommandHelp:
    """Одна строка справки: команда, зачем она и как выглядит в жизни."""

    command: str
    purpose: str
    example: str


# Порядок — порядок в карточке: сначала «как начать», потом основные действия.
# `start` и `help` включены явно: иначе тест на дрейф пришлось бы ослаблять до
# «все команды, кроме служебных», и новая команда могла бы спрятаться.
COMMANDS: tuple[CommandHelp, ...] = (
    CommandHelp("/start", "приветствие и эта справка", "/start"),
    CommandHelp("/help", "эта справка", "/help"),
    CommandHelp("/new", "создать тренировку", "/new strength Пн,Ср,Пт 19:30"),
    CommandHelp("/list", "показать расписание", "/list"),
    CommandHelp("/off", "отключить тренировку", "/off 2"),
    CommandHelp("/history", "последние отметки", "/history"),
    CommandHelp("/wellness", "самочувствие за сегодня", "/wellness 3 не выспался"),
    CommandHelp("/plan", "план на завтра", "/plan"),
)

FREE_TEXT_EXAMPLES: tuple[tuple[str, str], ...] = (
    ("силовая пн ср пт в 19:30", "/new strength Пн,Ср,Пт 19:30"),
    ("кардио по вторникам и четвергам в восемь утра", "/new cardio Вт,Чт 08:00"),
    ("покажи расписание", "/list"),
    ("убери вторую тренировку", "/off 2"),
)

# Фразы уже в нормализованном виде: нижний регистр, без пунктуации.
# Список короткий намеренно: расширяем по реальным случаям, а не заранее —
# каждая фраза здесь отнимается у ассистента.
HELP_TRIGGERS: frozenset[str] = frozenset(
    {
        "помоги",
        "помощь",
        "help",
        "инструкция",
        "что ты умеешь",
        "как пользоваться",
        "какие команды",
    }
)

# Три фразы для самой карточки: полный набор живёт в `HELP_TRIGGERS`, но
# перечислять в тексте все семь — шум. Подмножество проверяется тестом.
HELP_TRIGGER_HINT: tuple[str, ...] = ("помоги", "инструкция", "что ты умеешь")


def normalize(text: str) -> str:
    """Привести фразу к сравнимому виду: регистр, ё, пунктуация, пробелы."""
    lowered = text.strip().lower().replace("ё", "е")
    without_punctuation = _PUNCTUATION.sub(" ", lowered)
    return _SPACES.sub(" ", without_punctuation).strip()


def is_help_request(text: str) -> bool:
    """True, только если фраза целиком просит справку.

    Полное совпадение, а не вхождение: «помоги составить тренировку на среду» —
    это запрос к ассистенту, и отбирать его у модели нельзя.
    """
    return normalize(text) in HELP_TRIGGERS
